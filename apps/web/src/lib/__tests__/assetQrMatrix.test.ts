describe('Asset QR local encoder', () => {
  it('locks version 8 high-error-correction public URL matrix against a reference encoder', () => {
    const matrix = createAssetQrMatrix(SAMPLE_PUBLIC_URL);
    expect(ASSET_QR_VERSION).toBe(8);
    expect(ASSET_QR_ERROR_CORRECTION).toBe('H');
    expect(ASSET_QR_QUIET_ZONE).toBe(4);
    expect(matrix).toHaveLength(ASSET_QR_SIZE);
    expect(matrix.every((row) => row.length === ASSET_QR_SIZE)).toBe(true);
    expect(matrix.map((row) => row.map((value) => value ? '1' : '0').join('')).join('\n')).toBe(REFERENCE_MATRIX);
  });

  it('builds a public HTTPS route whose only identifier is the random UUID', () => {
    expect(buildAssetQrPublicUrl(SAMPLE_PUBLIC_ID, 'https://smartlab.example'))
      .toBe(SAMPLE_PUBLIC_URL);
    expect(() => buildAssetQrPublicUrl('asset-01', 'https://smartlab.example')).toThrow(AssetQrMatrixError);
    expect(() => buildAssetQrPublicUrl(SAMPLE_PUBLIC_ID, 'javascript:alert(1)')).toThrow(AssetQrMatrixError);
  });

  it('fails closed when the canonical public URL exceeds the locked v8-H capacity', () => {
    expect(new TextEncoder().encode(SAMPLE_PUBLIC_URL).length).toBeLessThanOrEqual(ASSET_QR_MAX_PAYLOAD_BYTES);
    expect(() => createAssetQrMatrix('x'.repeat(ASSET_QR_MAX_PAYLOAD_BYTES + 1))).toThrow(AssetQrMatrixError);
  });

  it('renders only dark modules into the SVG path', () => {
    const matrix = createAssetQrMatrix(SAMPLE_PUBLIC_URL);
    const path = assetQrSvgPath(matrix);
    expect(path.startsWith('M0 0h1v1h-1z')).toBe(true);
    expect(path.length).toBeGreaterThan(1000);
    expect(path).not.toContain(SAMPLE_PUBLIC_ID);
  });
});

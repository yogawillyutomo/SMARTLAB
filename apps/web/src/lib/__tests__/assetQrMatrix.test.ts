describe('Asset QR local encoder', () => {
  it('locks version 5 high-error-correction matrix against a reference encoder', () => {
    const matrix = createAssetQrMatrix(SAMPLE_PUBLIC_ID);
    expect(ASSET_QR_ERROR_CORRECTION).toBe('H');
    expect(ASSET_QR_QUIET_ZONE).toBe(4);
    expect(matrix).toHaveLength(ASSET_QR_SIZE);
    expect(matrix.every((row) => row.length === ASSET_QR_SIZE)).toBe(true);
    expect(matrix.map((row) => row.map((value) => value ? '1' : '0').join('')).join('\n')).toBe(REFERENCE_MATRIX);
  });

  it('rejects non-UUID and oversized payloads instead of silently changing QR capacity', () => {
    expect(() => createAssetQrMatrix('asset-01')).toThrow(AssetQrMatrixError);
    expect(() => createAssetQrMatrix('123e4567-e89b-12d3-a456-426614174000-extra')).toThrow(AssetQrMatrixError);
  });

  it('renders only dark modules into the SVG path', () => {
    const matrix = createAssetQrMatrix(SAMPLE_PUBLIC_ID);
    const path = assetQrSvgPath(matrix);
    expect(path.startsWith('M0 0h1v1h-1z')).toBe(true);
    expect(path.length).toBeGreaterThan(1000);
    expect(path).not.toContain(SAMPLE_PUBLIC_ID);
  });
});
